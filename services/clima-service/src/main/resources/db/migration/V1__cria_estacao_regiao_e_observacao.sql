-- V1 · estações do INMET, regiões climáticas (Região N—1 Estação) e observações horárias (Estação 1—N Observação).
-- As regras do domínio também viram restrições no banco: a última linha de defesa contra um INSERT fora da aplicação.

CREATE TABLE estacao (
    codigo     VARCHAR(8)       PRIMARY KEY,
    nome       VARCHAR(80)      NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude  DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    altitude_m DOUBLE PRECISION
);

CREATE TABLE regiao_climatica (
    codigo         VARCHAR(40) PRIMARY KEY,
    nome           VARCHAR(80) NOT NULL,
    estacao_codigo VARCHAR(8)  NOT NULL REFERENCES estacao (codigo)
);

CREATE INDEX ix_regiao_climatica_estacao ON regiao_climatica (estacao_codigo);

CREATE TABLE observacao (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estacao_codigo    VARCHAR(8)       NOT NULL REFERENCES estacao (codigo),
    observada_em      TIMESTAMPTZ      NOT NULL,
    temperatura_c     DOUBLE PRECISION NOT NULL CHECK (temperatura_c BETWEEN -40 AND 60),
    umidade_pct       DOUBLE PRECISION NOT NULL CHECK (umidade_pct BETWEEN 0 AND 100),
    pressao_hpa       DOUBLE PRECISION,
    radiacao_kj_m2    DOUBLE PRECISION,
    vento_ms          DOUBLE PRECISION CHECK (vento_ms >= 0),
    precipitacao_mm   DOUBLE PRECISION CHECK (precipitacao_mm >= 0),
    indice_de_calor_c DOUBLE PRECISION NOT NULL,
    nivel             VARCHAR(16)      NOT NULL
        CHECK (nivel IN ('NORMAL', 'ATENCAO', 'CAUTELA_EXTREMA', 'PERIGO', 'PERIGO_EXTREMO')),
    fonte             VARCHAR(12)      NOT NULL CHECK (fonte IN ('INMET', 'OPEN_METEO')),
    -- uma observação por estação e por hora: reingerir a mesma hora não duplica
    CONSTRAINT uq_observacao_estacao_hora UNIQUE (estacao_codigo, observada_em)
);
